// Generates words/en.js and words/he.js from FrequencyWords (Hermit Dave, CC-BY-SA 4.0).
import fs from 'node:fs';

const list = f => fs.readFileSync(new URL(f, import.meta.url), 'utf8')
  .split('\n').map(s => s.trim()).filter(s => s && !s.startsWith('#'));
const two = new Set(list('./en-two-letter.txt'));
const block = new Set(list('./blocklist.txt'));

const langs = {
  en: w => { w = w.toLowerCase(); return /^[a-z]{2,}$/.test(w) && (w.length > 2 || two.has(w)) ? w : null; },
  he: w => (/^[א-ת]{2,}$/.test(w) ? w : null),
};

const G = "(typeof window !== 'undefined' ? window : globalThis)";
for (const [lang, keep] of Object.entries(langs)) {
  const url = `https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/${lang}/${lang}_50k.txt`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  const words = [...new Set((await res.text()).split('\n').map(l => keep(l.split(' ')[0])).filter(Boolean))];
  const valid = words.slice(0, 30000);
  const common = words.slice(0, 3000).filter(w => !block.has(w));
  fs.writeFileSync(new URL(`../words/${lang}.js`, import.meta.url),
    `// FrequencyWords by Hermit Dave, CC-BY-SA 4.0. Generated by tools/build-words.mjs; do not edit.\n` +
    `${G}.WORDS = ${G}.WORDS || {};\n` +
    `${G}.WORDS.${lang} = { valid: ${JSON.stringify(valid.join(' '))}, common: ${JSON.stringify(common.join(' '))} };\n`);
  console.log(lang, valid.length, common.length);
}
